export function scnFieldsInSection(section: ScnSection): ScnField[] {
  return SCN_FIELDS.filter((f) => f.section === section);
}

export function scnField(key: string): ScnField | undefined {
  return SCN_FIELDS.find((f) => f.key === key);
}

/** The field's label, by key — the one place a label comes from. */
export function scnFieldLabel(key: string): string {
  return scnField(key)?.label ?? key;
}

