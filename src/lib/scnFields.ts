// =============================================================================
// SCN Dashboard — the columns, as DATA.
//
// Declared once here and the mapper, the write payload, the $select, the
// detail cards and the FieldEditModal specs are all driven from it — the same
// arrangement as grayMarketFields.ts, and for the same reason: several of the
// internal names do NOT say what they mean, and a label typed into a view is
// how two screens end up calling one column different things.
//
// Column names come from the live list (scripts/scn-dashboard-schema.json,
// captured 2026-10-07). The ones that lie:
//
//   Progress        → the PRODUCT name, not a progress value
//   Priority        → the CATEGORY (OBS / PHASE OUT / EECR / Notification)
//   PartsEffected   → labelled "Old Number"
//   EOLExpires      → labelled "LTS Expires"
//   Title           → the SCN# (YYYY-NNNN), generated by lib/scnNumber.ts
//
// Guessing any of those from the label writes to a column that doesn't
// exist — which SharePoint accepts silently on some paths and 400s on others.
// =============================================================================

/**
 * Where a field is shown. The four CARD sections are the detail page's
 * cards, in order; "Sidebar" holds the header/sidebar controls (status,
 * approval, the two person columns), which have their own rendering.
 */
export type ScnSection = "Notice" | "Parts" | "Review" | "Outcome" | "Sidebar";

/** The detail page's cards, in order. The sidebar is not a card. */
export const SCN_SECTIONS: ScnSection[] = ["Notice", "Parts", "Review", "Outcome"];

/**
 *  text / multiline / choice  → a string, in `Scn.values` (or a NAMED field —
 *                               see `named`)
 *  multiChoice                → a string[], in `Scn.checks`
 *  date                       → a Date | null, in `Scn.dates`
 *  person                     → a Person[], a named field (assignedTo / owner)
 *  link                       → a Hyperlink column, read-only (`Scn.taskList`)
 */
export type ScnFieldKind =
  | "text"
  | "multiline"
  | "choice"
  | "multiChoice"
  | "date"
  | "person"
  | "link";

export interface ScnField {
  /** Domain key — `Scn.values[key]` / `Scn.checks[key]` / `Scn.dates[key]`, or the named field. */
  key: string;
  /** SharePoint internal column name — the thing that must be exact. */
  column: string;
  /** The label to SHOW. Where it differs from the column's own display name, this one wins. */
  label: string;
  kind: ScnFieldKind;
  section: ScnSection;
  /** Choice / multi-choice options, verbatim from the column definition. */
  options?: readonly string[];
  /** Read and shown, never written (`Task_x0020_List`). */
  readOnly?: boolean;
  /** SharePoint refuses a blank on create (`ApprovalStatus`). */
  required?: boolean;
  /** The column's own cap (`ECN` is 10 characters). */
  maxLength?: number;
  /**
   * A string column that lives as a NAMED property on `Scn` (product,
   * category, status, approvalStatus) rather than in `values` — they are the
   * list's columns, the sidebar's controls and the header's chips, so a
   * named property is what every screen sorts and filters on.
   */
  named?: boolean;
  /**
   * A TEXT column filled from Engineering's Project References and stored as
   * the project's title (`lib/scnProjects.ts`). It can't be a real lookup —
   * the Projects list is in another site collection.
   */
  project?: boolean;
}

