/** A part as SAP has it. Every figure is nullable: SAP may not hold it yet. */
export interface SapPart {
  altronicPartNumber: string;
  sapPartNumber: string;
  description: string;
  mpg: string;
  listPrice: number | null;
  cost: number | null;
}

export interface SapCustomer {
  soldTo: string;
  name: string;
  customerGroup: string;
}
