import type { Comment, Person } from "./task";

// =============================================================================
// Sales Pricing (BusinessIT#47) — domain types for the four lists on the
// ALTRONICSALESTEAM site, and for the SAP facts read from the Fabric warehouse.
//
// Where each lives decides who can read it, and that is the design:
//   - PricingRequest      every pricing role — the FINAL price only.
//   - PricingHistoryRecord, NewProductWorksheet
//                         managers and admins only — cost, margin, reasoning.
// SharePoint's list permissions are the real boundary; ARC's gating is UI.
// =============================================================================

// -----------------------------------------------------------------------------
// Roles
// -----------------------------------------------------------------------------

/** Each tag implies the ones before it: admin ⊃ manager ⊃ requester. */
export const PRICING_ROLES = ["requester", "manager", "admin"] as const;
export type PricingRole = (typeof PRICING_ROLES)[number];

export interface PricingRoleEntry {
  id: number;
  /** Title — matched on address, never on a name. */
  email: string;
  /** PersonName — never DisplayName (Graph silently drops that field). */
  displayName: string;
  roles: PricingRole[];
  note: string;
}

// -----------------------------------------------------------------------------
// Requests
// -----------------------------------------------------------------------------

export const PRICING_REQUEST_STATUSES = [
  "Awaiting SAP",
  "Submitted",
  "In Review",
  "Priced",
  "Cancelled",
] as const;
export type PricingRequestStatus = (typeof PRICING_REQUEST_STATUSES)[number];

/** Statuses still waiting on somebody — the Dashboard card's count. */
export const OPEN_PRICING_STATUSES: readonly PricingRequestStatus[] = ["Awaiting SAP", "Submitted", "In Review"];

export interface PricingRequest {
  id: number;
  /** Title — PR-YYYY-####, generated by ARC. */
  requestNumber: string;
  status: PricingRequestStatus;
  altronicPartNumber: string;
  sapPartNumber: string;
  /** What the requester typed. Never overwritten. */
  requestedDescription: string;
  /** The current description — SAP's, once ARC has found the part. */
  description: string;
  /** Material price group, from SAP. */
  mpg: string;
  requestedBy: Person | null;
  notes: string;
  customerSoldTo: string;
  customerName: string;
  customerGroup: string;
  /** The outcome — readable by every role. Cost and margin are NOT here. */
  listPrice: number | null;
  customerDiscountPct: number | null;
  customerPrice: number | null;
  pricedBy: Person | null;
  pricedAt: string | null;
  addedToSapBy: Person | null;
  addedToSapAt: string | null;
  cancelReason: string;
  comments: Comment[];
  watchers: Person[];
  hasAttachments: boolean;
  createdBy: Person | null;
  createdAt: string | null;
  modifiedAt: string | null;
}

// -----------------------------------------------------------------------------
// How a price was reached (managers and admins only)
// -----------------------------------------------------------------------------

export const COST_SOURCES = ["SAP", "Manual"] as const;
export type CostSource = (typeof COST_SOURCES)[number];

export const DISCOUNT_SOURCES = ["SAP", "Default", "Manual"] as const;
export type DiscountSource = (typeof DISCOUNT_SOURCES)[number];

/** What the manager typed: a target base GM, or a list price. */
export interface PriceInput {
  kind: "gm" | "list";
  value: number;
}

/** One comparison panel, as saved — the SUMMARY, never every row (Ray, 2026-10-13). */
export interface ComparablesSummary {
  /** The MPG, or the six-digit family prefix. */
  key: string;
  averageGM: number | null;
  counted: number;
}

/** One pricing of a request — an entry in Pricing History's JSON column. */
export interface PricingHistoryEntry {
  pricedAt: string;
  pricedBy: { displayName: string; email: string };
  cost: number;
  costSource: CostSource;
  distributorDiscountPct: number;
  discountSource: DiscountSource;
  input: PriceInput;
  listPrice: number;
  baseGM: number | null;
  customerGroup: string;
  customerDiscountPct: number | null;
  customerPrice: number | null;
  customerGM: number | null;
  mpg: ComparablesSummary | null;
  family: ComparablesSummary | null;
  note: string;
}

/** The Pricing History row for one request — the latest pricing as columns, every pricing in `history`. */
export interface PricingHistoryRecord {
  id: number;
  requestNumber: string;
  requestId: number | null;
  cost: number | null;
  costSource: CostSource | null;
  distributorDiscountPct: number | null;
  discountSource: DiscountSource | null;
  targetGM: number | null;
  listPrice: number | null;
  baseGM: number | null;
  customerGM: number | null;
  mpg: string;
  mpgAvgGM: number | null;
  mpgCount: number | null;
  familyPrefix: string;
  familyAvgGM: number | null;
  familyCount: number | null;
  pricingNote: string;
  /** Oldest first. */
  history: PricingHistoryEntry[];
  /** The stored JSON couldn't be read — ARC refuses to write over it. */
  historyCorrupt: boolean;
}

// -----------------------------------------------------------------------------
// New Product Pricing (managers and admins only)
// -----------------------------------------------------------------------------

export const NEW_PRODUCT_STATUSES = ["Active", "Cancelled"] as const;
export type NewProductStatus = (typeof NEW_PRODUCT_STATUSES)[number];

/** Where a BOM line's cost came from. An estimate is typed for a part not in SAP. */
export type BomCostSource = "SAP" | "Estimate";

export interface BomLine {
  /** Stable within a worksheet — React keys and edits. */
  id: string;
  partNumber: string;
  description: string;
  quantity: number;
  unitCost: number | null;
  costSource: BomCostSource;
}

/** A quantity break: at `minQty` or more, `discountPct` off list. */
export interface PriceBreakTier {
  minQty: number;
  discountPct: number;
}

/** A break with its price and margin worked out. */
export interface PricedBreak extends PriceBreakTier {
  price: number;
  baseGM: number | null;
}

/** One revision's full snapshot — an entry in the worksheet's JSON history. */
export interface NewProductRevision {
  rev: number;
  savedAt: string;
  savedBy: { displayName: string; email: string };
  /** What changed in this revision. Required when a revision is started. */
  note: string;
  bom: BomLine[];
  overheadPct: number;
  unitCost: number | null;
  mpg: string;
  distributorDiscountPct: number;
  discountSource: DiscountSource;
  input: PriceInput | null;
  listPrice: number | null;
  baseGM: number | null;
  priceBreaks: PricedBreak[];
}

export interface NewProductWorksheet {
  id: number;
  /** Title — NP-YYYY-####, generated by ARC. */
  worksheetNumber: string;
  status: NewProductStatus;
  rev: number;
  productName: string;
  description: string;
  customerSoldTo: string;
  customerName: string;
  expectedAnnualVolume: number | null;
  /** The request a manager started this from, if any. */
  requestId: number | null;
  bom: BomLine[];
  overheadPct: number;
  mpg: string;
  distributorDiscountPct: number;
  discountSource: DiscountSource;
  targetGM: number | null;
  unitCost: number | null;
  listPrice: number | null;
  baseGM: number | null;
  priceBreaks: PriceBreakTier[];
  /** Remembered for Compare to SAP. */
  altronicPartNumber: string;
  sapPartNumber: string;
  /** One full snapshot per revision, oldest first. */
  history: NewProductRevision[];
  historyCorrupt: boolean;
  hasAttachments: boolean;
  createdBy: Person | null;
  createdAt: string | null;
  modifiedAt: string | null;
}

// -----------------------------------------------------------------------------
// SAP facts — read from the Fabric warehouse (api/pricingLookup.ts)
